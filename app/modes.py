def list_modes() -> list[dict[str, Any]]:
    return [
        {
            "key": key,
            "label": value["label"],
            "emoji": value["emoji"],
            "tagline": value["tagline"],
        }
        for key, value in MODES.items()
    ]


def build(mode: str, base: dict[str, Any]) -> dict[str, Any] | None:
    """Applique les surcharges du mode sur le preset de base."""
    if mode in ("", "custom", None):
        return dict(base)
    if mode not in MODES:
        return None
    preset = dict(base)
    preset.update(MODES[mode]["overrides"])
    return preset


def mode_label(mode: str) -> str:
    data = MODES.get(mode)
    if data is None:
        return "Personnalisé"
    return f"{data['emoji']} {data['label']}"
